-- -------------------------------------------------------------
-- 7. Voting (+1, -1, or 0 to clear)
-- -------------------------------------------------------------
create or replace function public.vote_forum_post(post uuid, vote smallint)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  me uuid := public.social_current_user();
  previous smallint;
  new_score integer;
begin
  if vote not in (-1, 0, 1) then
    raise exception 'Votes are +1, -1 or 0.';
  end if;

  perform 1 from public.forum_posts p where p.id = post and p.deleted_at is null for update;
  if not found then
    raise exception 'That post no longer exists.';
  end if;

  select v.value into previous from public.forum_post_votes v where v.post_id = post and v.user_id = me;

  if vote = 0 then
    delete from public.forum_post_votes where post_id = post and user_id = me;
  else
    insert into public.forum_post_votes (post_id, user_id, value) values (post, me, vote)
    on conflict (post_id, user_id) do update set value = excluded.value;
  end if;

  update public.forum_posts
  set score = score + vote - coalesce(previous, 0)
  where id = post
  returning score into new_score;

  return new_score;
end;
$$;

