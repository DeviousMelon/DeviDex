create or replace function public.list_forum_categories()
returns table (
  id smallint,
  slug text,
  name text,
  description text,
  admin_only_posts boolean,
  post_count bigint,
  last_activity_at timestamptz
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    c.id, c.slug, c.name, c.description, c.admin_only_posts,
    count(p.id) filter (where p.deleted_at is null),
    max(p.last_activity_at) filter (where p.deleted_at is null)
  from public.forum_categories c
  left join public.forum_posts p on p.category_id = c.id
  group by c.id
  order by c.sort_order, c.name;
