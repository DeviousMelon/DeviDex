create or replace function public.admin_set_forum_post_flags(post uuid, pinned boolean, locked boolean)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  if not public.is_admin() then
    raise exception 'Only admins can pin or lock posts.';
  end if;

  update public.forum_posts
  set is_pinned = coalesce(pinned, is_pinned), is_locked = coalesce(locked, is_locked)
  where id = post and deleted_at is null;

  if not found then
    raise exception 'That post no longer exists.';
  end if;
end;
$$;

-- content_kind: 'post' or 'comment'. The original text is kept in any report
-- snapshot, so removing it here does not destroy the evidence.
create or replace function public.admin_remove_forum_content(content_kind text, content uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  post uuid;
begin
  if not public.is_admin() then
    raise exception 'Only admins can remove forum content.';
  end if;

  if content_kind = 'post' then
    update public.forum_posts
    set deleted_at = coalesce(deleted_at, now()), removed_by_admin = true, is_pinned = false
    where id = content;
  elsif content_kind = 'comment' then
    update public.forum_comments
    set deleted_at = now(), removed_by_admin = true
    where id = content and deleted_at is null
    returning post_id into post;
    if post is not null then
      update public.forum_posts set comment_count = greatest(comment_count - 1, 0) where id = post;
    end if;
  else
    raise exception 'Unknown content type.';
  end if;
end;
$$;

-- -------------------------------------------------------------
-- 9. Reports now cover forum posts and comments
-- -------------------------------------------------------------
create or replace function public.submit_report(
  report_target_type text,
  report_target_id uuid,
  report_reason text,
  report_details text default null
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  me uuid := auth.uid();
  offender uuid;
  offender_name text;
  snapshot text;
  new_id uuid;
begin
  if me is null then
    raise exception 'You must be signed in to report something.';
  end if;

  if (select count(*) from public.reports r where r.reporter_id = me and r.created_at > now() - interval '1 day') >= 20 then
    raise exception 'You have sent a lot of reports today. Try again tomorrow.';
  end if;

  if report_target_type = 'user' then
    select p.id, p.username into offender, offender_name
    from public.profiles p where p.id = report_target_id;
    snapshot := null;
  elsif report_target_type = 'message' then
    select msg.sender_id, p.username, msg.body into offender, offender_name, snapshot
    from public.messages msg
    left join public.profiles p on p.id = msg.sender_id
    join public.conversation_members m on m.conversation_id = msg.conversation_id and m.user_id = me
    where msg.id = report_target_id and msg.kind = 'text' and msg.deleted_at is null;
  elsif report_target_type = 'forum_post' then
    select fp.author_id, p.username, fp.title || E'\n\n' || fp.body into offender, offender_name, snapshot
    from public.forum_posts fp
    left join public.profiles p on p.id = fp.author_id
    where fp.id = report_target_id and fp.deleted_at is null;
  elsif report_target_type = 'forum_comment' then
    select fc.author_id, p.username, fc.body into offender, offender_name, snapshot
    from public.forum_comments fc
    left join public.profiles p on p.id = fc.author_id
    where fc.id = report_target_id and fc.deleted_at is null;
  else
    raise exception 'That kind of report is not supported.';
  end if;

  if offender is null then
    raise exception 'That no longer exists, or you cannot see it.';
  end if;

  if offender = me then
    raise exception 'You cannot report yourself.';
  end if;

  insert into public.reports (
    reporter_id, target_type, target_id, target_user_id, target_username,
    content_snapshot, reason, details
  )
  values (
    me, report_target_type, report_target_id, offender, offender_name,
    left(snapshot, 4000), report_reason, nullif(btrim(report_details), '')
  )
  returning id into new_id;

  return new_id;
exception
  when unique_violation then
    select r.id into new_id
    from public.reports r
    where r.reporter_id = me
      and r.target_type = report_target_type
      and r.target_id = report_target_id
      and r.status = 'open';
    return new_id;
end;
$$;

-- -------------------------------------------------------------
-- 10. Function permissions
-- -------------------------------------------------------------
do $$
declare
  fn text;
begin
  -- Readable by everyone, including signed-out visitors.
  foreach fn in array array[
    'public.list_forum_categories()',
    'public.list_forum_posts(text, text, integer, integer)',
    'public.get_forum_post(uuid)',
    'public.get_forum_comments(uuid)'
  ] loop
    execute format('revoke all on function %s from public', fn);
    execute format('grant execute on function %s to anon, authenticated', fn);
  end loop;

  -- Signed-in only.
  foreach fn in array array[
    'public.create_forum_post(text, text, text, bigint)',
    'public.edit_forum_post(uuid, text, text)',
    'public.delete_forum_post(uuid)',
    'public.create_forum_comment(uuid, uuid, text)',
    'public.edit_forum_comment(uuid, text)',
    'public.delete_forum_comment(uuid)',
    'public.vote_forum_post(uuid, smallint)',
    'public.vote_forum_comment(uuid, smallint)',
    'public.admin_set_forum_post_flags(uuid, boolean, boolean)',
    'public.admin_remove_forum_content(text, uuid)',
    'public.submit_report(text, uuid, text, text)'
  ] loop
    execute format('revoke all on function %s from public, anon', fn);
    execute format('grant execute on function %s to authenticated', fn);
  end loop;
end;
$$;
