-- -------------------------------------------------------------
-- 5. Writing posts
-- -------------------------------------------------------------
create or replace function public.create_forum_post(
  category text,
  post_title text,
  post_body text,
  shared_form_id bigint default null
)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  me uuid := public.social_current_user();
  target public.forum_categories%rowtype;
  clean_title text := btrim(coalesce(post_title, ''));
  clean_body text := btrim(coalesce(post_body, ''));
  new_id uuid;
begin
  select * into target from public.forum_categories c where c.slug = category;
  if target.id is null then
    raise exception 'That forum does not exist.';
  end if;
  if target.admin_only_posts and not public.is_admin() then
    raise exception 'Only admins can post in %.', target.name;
  end if;
  if char_length(clean_title) < 3 or char_length(clean_title) > 120 then
    raise exception 'Titles need 3–120 characters.';
  end if;
  if char_length(clean_body) > 10000 then
    raise exception 'Posts can be up to 10,000 characters.';
  end if;
  if shared_form_id is not null and not exists (select 1 from public.pokemon_forms f where f.id = shared_form_id) then
    raise exception 'That Pokémon is not in the DeviDex catalogue.';
  end if;
  if (select count(*) from public.forum_posts p where p.author_id = me and p.created_at > now() - interval '1 hour') >= 5 then
    raise exception 'You can post 5 times an hour. Try again a bit later.';
  end if;

  insert into public.forum_posts (category_id, author_id, title, body, pokemon_form_id)
  values (target.id, me, clean_title, clean_body, shared_form_id)
  returning id into new_id;

  return new_id;
end;
$$;

create or replace function public.edit_forum_post(post uuid, post_title text, post_body text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  clean_title text := btrim(coalesce(post_title, ''));
  clean_body text := btrim(coalesce(post_body, ''));
begin
  if char_length(clean_title) < 3 or char_length(clean_title) > 120 then
    raise exception 'Titles need 3–120 characters.';
  end if;
  if char_length(clean_body) > 10000 then
    raise exception 'Posts can be up to 10,000 characters.';
