-- =============================================================
-- DeviDex v1.9 - Social phase 4: forums
--
-- Run AFTER v1.8. Safe to rerun during development.
--
-- Reddit-style: categories, posts, threaded comments and up/down votes.
-- - Anyone (even signed out) can read. Posting, commenting and voting need an
--   account with a username.
-- - Tables are not readable directly. Reads go through functions that attach
--   author names, your own vote, and flag authors you have blocked.
-- - Deleting is soft: the post/comment stays as "[deleted]" so threads keep
--   their shape. Admins can remove anything and pin or lock posts.
-- =============================================================

-- -------------------------------------------------------------
-- 1. Tables
-- -------------------------------------------------------------
create table if not exists public.forum_categories (
  id smallint generated by default as identity primary key,
  slug text not null unique check (slug ~ '^[a-z0-9-]{2,40}$'),
  name text not null check (char_length(name) between 2 and 60),
  description text check (description is null or char_length(description) <= 240),
  sort_order integer not null default 0,
  -- Locked categories (e.g. Announcements) only accept posts from admins.
  admin_only_posts boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.forum_posts (
  id uuid primary key default gen_random_uuid(),
  category_id smallint not null references public.forum_categories(id) on delete restrict,
  author_id uuid references public.profiles(id) on delete set null,
  title text not null check (char_length(title) between 1 and 120),
  body text not null check (char_length(body) <= 10000),
  pokemon_form_id bigint references public.pokemon_forms(id) on delete set null,
  is_pinned boolean not null default false,
  is_locked boolean not null default false,
  score integer not null default 0,
  comment_count integer not null default 0,
  created_at timestamptz not null default now(),
  edited_at timestamptz,
  last_activity_at timestamptz not null default now(),
  deleted_at timestamptz,
  removed_by_admin boolean not null default false
);

create index if not exists forum_posts_category_activity_idx on public.forum_posts (category_id, last_activity_at desc);
create index if not exists forum_posts_created_idx on public.forum_posts (created_at desc);
create index if not exists forum_posts_author_idx on public.forum_posts (author_id, created_at desc);

create table if not exists public.forum_comments (
  id uuid primary key default gen_random_uuid(),
  post_id uuid not null references public.forum_posts(id) on delete cascade,
  parent_id uuid references public.forum_comments(id) on delete cascade,
  author_id uuid references public.profiles(id) on delete set null,
  body text not null check (char_length(body) <= 5000),
  depth smallint not null default 0 check (depth between 0 and 8),
  score integer not null default 0,
  created_at timestamptz not null default now(),
  edited_at timestamptz,
  deleted_at timestamptz,
  removed_by_admin boolean not null default false
);

create index if not exists forum_comments_post_idx on public.forum_comments (post_id, created_at);
create index if not exists forum_comments_author_idx on public.forum_comments (author_id, created_at desc);

create table if not exists public.forum_post_votes (
  post_id uuid not null references public.forum_posts(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  value smallint not null check (value in (-1, 1)),
  primary key (post_id, user_id)
);

create table if not exists public.forum_comment_votes (
  comment_id uuid not null references public.forum_comments(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  value smallint not null check (value in (-1, 1)),
  primary key (comment_id, user_id)
);

create index if not exists forum_post_votes_user_idx on public.forum_post_votes (user_id);
create index if not exists forum_comment_votes_user_idx on public.forum_comment_votes (user_id);

