-- -------------------------------------------------------------
-- 6. Comments
-- -------------------------------------------------------------
create or replace function public.create_forum_comment(post uuid, parent uuid, comment_body text)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  me uuid := public.social_current_user();
  target public.forum_posts%rowtype;
  parent_row public.forum_comments%rowtype;
  clean_body text := btrim(coalesce(comment_body, ''));
  new_id uuid;
begin
  select * into target from public.forum_posts p where p.id = post for update;

  if target.id is null or target.deleted_at is not null then
    raise exception 'That post no longer exists.';
  end if;
  if target.is_locked and not public.is_admin() then
    raise exception 'This post is locked, so it is not taking new comments.';
  end if;
  if clean_body = '' then
    raise exception 'Write something first.';
  end if;
  if char_length(clean_body) > 5000 then
    raise exception 'Comments can be up to 5,000 characters.';
  end if;

  if parent is not null then
    select * into parent_row from public.forum_comments c where c.id = parent and c.post_id = post;
    if parent_row.id is null then
      raise exception 'The comment you replied to no longer exists.';
    end if;
    if parent_row.deleted_at is not null then
      raise exception 'You cannot reply to a deleted comment.';
    end if;
  end if;

  -- Blocking works both ways in replies: you cannot reply to someone you
  -- blocked, or who blocked you.
  if public.is_blocked_between(me, coalesce(parent_row.author_id, target.author_id)) then
    raise exception 'You cannot reply to this person.';
  end if;

  if (select count(*) from public.forum_comments c where c.author_id = me and c.created_at > now() - interval '1 hour') >= 60 then
    raise exception 'You have commented a lot this hour. Take a breather.';
  end if;

  insert into public.forum_comments (post_id, parent_id, author_id, body, depth)
  values (
    post,
    -- Very deep threads attach to the deepest allowed level instead of failing.
    case when parent_row.depth >= 8 then parent_row.parent_id else parent end,
    me,
    clean_body,
    least(coalesce(parent_row.depth + 1, 0), 8)
  )
  returning id into new_id;

  update public.forum_posts
  set comment_count = comment_count + 1, last_activity_at = now()
  where id = post;

  return new_id;
end;
$$;

