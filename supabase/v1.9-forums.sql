-- Whether the signed-in viewer blocked this author (their content is folded
-- away rather than removed, so threads still make sense).
create or replace function public.forum_viewer_blocked(author uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select auth.uid() is not null and author is not null and exists (
    select 1 from public.user_blocks b where b.blocker_id = auth.uid() and b.blocked_id = author
  );
$$;

revoke all on function public.forum_viewer_blocked(uuid) from public, anon, authenticated;

