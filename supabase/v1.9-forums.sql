-- One shape for list rows and the single-post view.
create or replace function public.forum_post_rows(only_post uuid, category_filter text, sort_by text, page_limit integer, page_offset integer)
returns table (
  id uuid,
  category_slug text,
  category_name text,
  title text,
  body text,
  pokemon_form_id bigint,
  is_pinned boolean,
  is_locked boolean,
  score integer,
  comment_count integer,
  created_at timestamptz,
  edited_at timestamptz,
  last_activity_at timestamptz,
  is_deleted boolean,
  removed_by_admin boolean,
  author_id uuid,
  author_username text,
  author_display_name text,
  author_avatar_path text,
  author_profile_updated_at timestamptz,
  author_is_admin boolean,
  author_blocked boolean,
  my_vote smallint
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    p.id, c.slug, c.name,
    case when p.deleted_at is null then p.title else '[deleted]' end,
    case when p.deleted_at is null then p.body else '' end,
    case when p.deleted_at is null then p.pokemon_form_id end,
    p.is_pinned, p.is_locked, p.score, p.comment_count,
    p.created_at, p.edited_at, p.last_activity_at,
    p.deleted_at is not null, p.removed_by_admin,
    case when p.deleted_at is null then a.id end,
    case when p.deleted_at is null then a.username end,
    case when p.deleted_at is null then a.display_name end,
    case when p.deleted_at is null then a.avatar_path end,
    case when p.deleted_at is null then a.updated_at end,
    coalesce(p.deleted_at is null and a.role = 'admin', false),
    public.forum_viewer_blocked(p.author_id),
    (select v.value from public.forum_post_votes v where v.post_id = p.id and v.user_id = auth.uid())
  from public.forum_posts p
  join public.forum_categories c on c.id = p.category_id
  left join public.profiles a on a.id = p.author_id
  where (only_post is not null and p.id = only_post)
     or (
       only_post is null
       and p.deleted_at is null
       and (category_filter is null or c.slug = category_filter)
     )
  order by
    -- Pinned posts lead inside a category; on the all-categories feed only
    -- Announcements pins do.
    case when only_post is null and p.is_pinned and (category_filter is not null or c.admin_only_posts) then 0 else 1 end,
    case sort_by
      when 'top' then -p.score::double precision
      when 'new' then -extract(epoch from p.created_at)
      -- 'hot': score decays with age, like Reddit's front page.
      else -((p.score + 1) / power(extract(epoch from (now() - p.created_at)) / 3600 + 2, 1.5))
    end,
    p.created_at desc
  limit greatest(1, least(coalesce(page_limit, 25), 100))
  offset greatest(0, coalesce(page_offset, 0));
$$;

revoke all on function public.forum_post_rows(uuid, text, text, integer, integer) from public, anon, authenticated;

