-- -----------------------------
-- Master Pokémon species table
-- -----------------------------
create table if not exists public.pokemon_species (
  id integer primary key,
  national_dex_number integer not null unique,
  slug text not null unique,
  name text not null,
  generation integer not null check (generation between 1 and 20),
  is_legendary boolean not null default false,
  is_mythical boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Forms are separate from species because a serious Living Dex needs to be
-- able to decide which alternate appearances count as their own stored entry.
create table if not exists public.pokemon_forms (
  id bigint generated by default as identity primary key,
  species_id integer not null references public.pokemon_species(id) on delete cascade,
  slug text not null unique,
  name text not null,
  is_default boolean not null default false,
  is_trackable boolean not null default false,
  form_order integer not null default 0,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (species_id, slug)
);

-- Game metadata is deliberately independent from collection progress. Later
-- releases and spin-off support can be added without changing user saves.
create table if not exists public.games (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  generation integer not null check (generation between 1 and 20),
  release_order integer not null default 0,
  is_main_series boolean not null default true,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Regional/game Pokédex membership. We track species here because most game
-- Pokédex numbering is species-based even when alternate forms exist.
create table if not exists public.game_dex_entries (
  game_id bigint not null references public.games(id) on delete cascade,
  species_id integer not null references public.pokemon_species(id) on delete cascade,
  dex_number integer,
  created_at timestamptz not null default now(),
  primary key (game_id, species_id)
);

-- This is the lightweight progress layer for the core Living/Shiny/Form Dex.
-- Detailed individual specimens/origin games will be a separate layer later,
-- so we do not force one database row to represent an actual Pokémon forever.
create table if not exists public.collection_progress (
  user_id uuid not null references auth.users(id) on delete cascade,
  form_id bigint not null references public.pokemon_forms(id) on delete cascade,
  normal_owned boolean not null default false,
  shiny_owned boolean not null default false,
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (user_id, form_id)
);

create index if not exists pokemon_forms_species_idx on public.pokemon_forms(species_id);
create index if not exists pokemon_forms_trackable_idx on public.pokemon_forms(is_trackable, form_order);
create index if not exists collection_progress_user_idx on public.collection_progress(user_id);
create index if not exists collection_progress_form_idx on public.collection_progress(form_id);

-- ------------------------------------------------------------
-- updated_at helper
-- ------------------------------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists pokemon_species_set_updated_at on public.pokemon_species;
create trigger pokemon_species_set_updated_at
before update on public.pokemon_species
for each row execute procedure public.set_updated_at();

drop trigger if exists pokemon_forms_set_updated_at on public.pokemon_forms;
create trigger pokemon_forms_set_updated_at
before update on public.pokemon_forms
for each row execute procedure public.set_updated_at();

drop trigger if exists games_set_updated_at on public.games;
create trigger games_set_updated_at
before update on public.games
for each row execute procedure public.set_updated_at();

drop trigger if exists collection_progress_set_updated_at on public.collection_progress;
create trigger collection_progress_set_updated_at
before update on public.collection_progress
for each row execute procedure public.set_updated_at();

