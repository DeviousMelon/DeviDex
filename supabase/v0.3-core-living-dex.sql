-- Master reference data is public-readable. This lets people browse DeviDex
-- without making an account first.
drop policy if exists "Anyone can read Pokemon species" on public.pokemon_species;
create policy "Anyone can read Pokemon species"
on public.pokemon_species for select
to anon, authenticated
using (true);

drop policy if exists "Anyone can read Pokemon forms" on public.pokemon_forms;
create policy "Anyone can read Pokemon forms"
on public.pokemon_forms for select
to anon, authenticated
using (true);

drop policy if exists "Anyone can read games" on public.games;
create policy "Anyone can read games"
on public.games for select
to anon, authenticated
using (true);

drop policy if exists "Anyone can read game dex entries" on public.game_dex_entries;
create policy "Anyone can read game dex entries"
on public.game_dex_entries for select
to anon, authenticated
using (true);

-- Only admins can change shared reference data.
drop policy if exists "Admins can insert Pokemon species" on public.pokemon_species;
create policy "Admins can insert Pokemon species"
on public.pokemon_species for insert to authenticated
with check (public.is_admin());

drop policy if exists "Admins can update Pokemon species" on public.pokemon_species;
create policy "Admins can update Pokemon species"
on public.pokemon_species for update to authenticated
using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Admins can delete Pokemon species" on public.pokemon_species;
create policy "Admins can delete Pokemon species"
on public.pokemon_species for delete to authenticated
using (public.is_admin());

drop policy if exists "Admins can insert Pokemon forms" on public.pokemon_forms;
create policy "Admins can insert Pokemon forms"
on public.pokemon_forms for insert to authenticated
with check (public.is_admin());

drop policy if exists "Admins can update Pokemon forms" on public.pokemon_forms;
create policy "Admins can update Pokemon forms"
on public.pokemon_forms for update to authenticated
using (public.is_admin()) with check (public.is_admin());

drop policy if exists "Admins can delete Pokemon forms" on public.pokemon_forms;
create policy "Admins can delete Pokemon forms"
on public.pokemon_forms for delete to authenticated
using (public.is_admin());

drop policy if exists "Admins can manage games" on public.games;
create policy "Admins can manage games"
