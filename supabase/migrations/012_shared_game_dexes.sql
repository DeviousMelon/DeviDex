-- Preserve existing users' homepage cards by treating already-started progress
-- as activity in that game's base shared Dex. DLC activity is intentionally NOT
-- inferred from species overlap; it starts when the user actually edits that DLC.
with candidates as (
  select
    gp.user_id,
    ds.id as set_id,
    gp.game_id,
    min(gp.created_at) as started_at,
    max(gp.updated_at) as last_activity_at
  from public.game_collection_progress gp
  join public.game_dex_set_members m on m.game_id = gp.game_id
  join public.game_dex_sets ds on ds.id = m.set_id and ds.scope_type = 'base'
  where gp.normal_owned = true or gp.shiny_owned = true
  group by gp.user_id, ds.id, gp.game_id
), chosen as (
  select distinct on (user_id, set_id)
    user_id, set_id, game_id, started_at, last_activity_at
  from candidates
  order by user_id, set_id, last_activity_at desc
)
insert into public.game_dex_activity (user_id, set_id, game_id, started_at, last_activity_at)
select user_id, set_id, game_id, started_at, last_activity_at
from chosen
on conflict (user_id, set_id) do nothing;

-- Public profile summaries now count explicitly started shared/DLC Dexes rather
-- than raw games. The rest of the privacy-preserving summary stays unchanged.
create or replace function public.get_public_collection_summary(candidate text)
returns table (
  living_owned bigint,
  shiny_owned bigint,
  trackable_total bigint,
  started_game_dexes bigint
)
language sql
stable
security definer
set search_path = ''
as $$
  with target as (
    select p.id
    from public.profiles p
    where p.username is not null
      and p.profile_public = true
      and p.collection_public = true
      and lower(p.username) = lower(btrim(candidate))
    limit 1
  ),
  prefs as (
    select
      t.id,
      coalesce(fp.include_regional, false) as regional,
      coalesce(fp.include_alternate, false) as alternate,
      coalesce(fp.include_pattern, false) as pattern,
      coalesce(fp.include_gender, false) as gender,
      coalesce(fp.include_battle, false) as battle,
      coalesce(fp.include_special, false) as special
    from target t
    left join public.user_form_preferences fp on fp.user_id = t.id
  ),
  eligible_forms as (
    select f.id
    from public.pokemon_forms f
    cross join prefs p
    where f.is_trackable = true
      and (
        f.form_category = 'default'
        or (f.form_category = 'regional' and p.regional)
        or (f.form_category = 'alternate' and p.alternate)
        or (f.form_category = 'pattern' and p.pattern)
        or (f.form_category = 'gender' and p.gender)
        or (f.form_category = 'battle' and p.battle)
        or (f.form_category = 'special' and p.special)
      )
  ),
  totals as (
    select count(*)::bigint as trackable_total from eligible_forms
  ),
  national as (
    select
      count(*) filter (where cp.normal_owned)::bigint as living_owned,
      count(*) filter (where cp.shiny_owned)::bigint as shiny_owned
    from public.collection_progress cp
    join target t on t.id = cp.user_id
    join eligible_forms ef on ef.id = cp.form_id
  ),
  games as (
    select count(*)::bigint as started_game_dexes
    from public.game_dex_activity a
    join target t on t.id = a.user_id
  )
  select
    coalesce(n.living_owned, 0),
    coalesce(n.shiny_owned, 0),
    totals.trackable_total,
    coalesce(g.started_game_dexes, 0)
  from target
  cross join totals
  cross join national n
  cross join games g;
$$;

