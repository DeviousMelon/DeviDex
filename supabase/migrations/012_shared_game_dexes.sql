-- A Game Dex set is the thing users browse: e.g. Scarlet / Violet,
-- Sword / Shield: Isle of Armor, or Platinum. Individual game rows remain
-- separate because user progress is still stored per version.
create table if not exists public.game_dex_sets (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  generation integer not null check (generation between 1 and 20),
  release_order integer not null default 0,
  scope_type text not null default 'base' check (scope_type in ('base', 'dlc', 'special')),
  parent_set_id bigint references public.game_dex_sets(id) on delete set null,
  region_label text,
  source_pokedex_slugs text[] not null default '{}',
  description text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.game_dex_set_members (
  set_id bigint not null references public.game_dex_sets(id) on delete cascade,
  game_id bigint not null references public.games(id) on delete cascade,
  member_order integer not null default 0,
  short_label text,
  created_at timestamptz not null default now(),
  primary key (set_id, game_id)
);

-- Shared catalogue membership. Forms deliberately remain out of this table;
-- Phase 6B will layer form membership on top of this stable species structure.
create table if not exists public.game_dex_set_entries (
  set_id bigint not null references public.game_dex_sets(id) on delete cascade,
  species_id integer not null references public.pokemon_species(id) on delete cascade,
  dex_number integer,
  dex_slug text not null,
  dex_name text not null,
  dex_order integer not null default 0,
  created_at timestamptz not null default now(),
  primary key (set_id, dex_slug, species_id)
);

create index if not exists game_dex_set_entries_order_idx
  on public.game_dex_set_entries(set_id, dex_order, dex_number);

-- This table stores only positive assertions about version exclusivity. If a
-- species has no row here, DeviDex does NOT claim it is obtainable in every
-- member game. Phase 8's acquisition data will eventually be the exhaustive
-- source of truth for catchability.
create table if not exists public.game_dex_version_exclusives (
  set_id bigint not null references public.game_dex_sets(id) on delete cascade,
  species_id integer not null references public.pokemon_species(id) on delete cascade,
  game_id bigint not null references public.games(id) on delete cascade,
  source text not null default 'curated',
  notes text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (set_id, species_id, game_id)
);

-- Explicit activity means the homepage knows which shared/DLC Dex was started.
-- It avoids incorrectly treating every DLC as started merely because its parent
-- game shares some of the same species progress.
create table if not exists public.game_dex_activity (
  user_id uuid not null references auth.users(id) on delete cascade,
  set_id bigint not null references public.game_dex_sets(id) on delete cascade,
  game_id bigint not null references public.games(id) on delete cascade,
  started_at timestamptz not null default now(),
  last_activity_at timestamptz not null default now(),
  primary key (user_id, set_id)
);

create index if not exists game_dex_activity_user_idx on public.game_dex_activity(user_id, last_activity_at desc);

-- updated_at support for new reference tables.
